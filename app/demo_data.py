def demo_videos(now: int | None = None) -> list[dict]:
    now = int(now or time.time())
    videos = []
    for i in range(55):
        category, tid, topic = CATALOG[i % len(CATALOG)]
        view = 48000 + (54 - i) * 7600
        like = int(view * (0.045 + (i % 4) * 0.008))
        reply = 126 if i == 0 else 12 + (i * 5) % 70
        share = max(1, int(like * 0.08))
        coin = max(1, int(like * 0.22))
        favorite = max(1, int(like * 0.31))
        videos.append(
            {
                "bvid": f"BV1demo{i:04d}",
                "aid": 860000000 + i,
                "title": f"【演示】{topic} · 样本{i + 1:02d}",
                "author": f"演示UP-{category}",
                "author_mid": 990000 + i,
                "category": category,
                "tid": tid,
                "cover_url": "",
                "description": "演示数据，不是 B 站实时统计。仅在无法访问 B 站接口时用于展示分析流程。",
                "view_count": view,
                "like_count": like,
                "comment_count": reply,
                "share_count": share,
                "coin_count": coin,
                "favorite_count": favorite,
                "pubdate": now - (8 + i) * 3600,
                "is_demo": True,
            }
        )
    return videos


def demo_comments(bvid: str = "BV1demo0000", now: int | None = None) -> list[dict]:
    now = int(now or time.time())
    comments = []
    for idx, line in enumerate(_ROWS):
        mid_s, uname, like_s, rcount_s, text = line.split("|", 4)
        comments.append(
            {
                "rpid": 9100000000 + idx + 1,
                "bvid": bvid,
                "root_rpid": 9100000000 + idx + 1,
                "parent_rpid": 0,
                "text": text,
                "ctime": now - (idx + 1) * 1800,
                "like": int(like_s),
                "rcount": int(rcount_s),
                "mid": int(mid_s),
                "uname": uname,
            }
        )
    return comments
